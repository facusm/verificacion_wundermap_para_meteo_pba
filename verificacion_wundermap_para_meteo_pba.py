#### función que lee los datos de cada EMA: viento medio, ráfagas, pp acumulada y hora local

def lectura_dataframe(estacion, fecha):
  url = f'https://www.wunderground.com/dashboard/pws/{estacion}/table/{fecha}/{fecha}/daily'
  #print(url)
  response = requests.get(url)
  soup = BeautifulSoup(response.content, 'html.parser')
  tabla = soup.find_all('table',attrs={'class':'history-table desktop-table'})[0]
  tabla = tabla.find_all('tbody',attrs={'_ngcontent-app-root-c3784113910':""})[0]
  rows = tabla.find_all('tr',attrs={'_ngcontent-app-root-c3784113910':""})
  #print(rows[0])

  data = []

  for row in rows:
      cols = row.find_all('span',attrs={'class':'wu-value wu-value-to'})
      cols = [col.text.strip() for col in cols]
      hora = row.find_all('strong',attrs={'_ngcontent-app-root-c3784113910':""})[0].text.strip()
      cols.insert(0, hora)
      data.append(cols)

  df_variables = pd.DataFrame(data)
  try:
    #df_variables.drop(columns=[1, 2, 3, 4, 7, 8, 10, 11], inplace=True)
    df_variables.rename(columns={4:'Viento_medio (km/h)', 5:'Rafagas (km/h)', 8:'Precipitacion (mm)', 0:'Hora_local'}, inplace=True)
  except:
    pass

  try:
    df_variables['Precipitacion (mm)'] = round(df_variables['Precipitacion (mm)'].astype(float)*25.4, 2) # Convierto pulgadas a milimetros
  except:
    pass
  try:
    df_variables['Rafagas (km/h)'] = round(df_variables['Rafagas (km/h)'].astype(float)*1.60934, 2) # Convierto millas por hora a kilometros por hora
  except:
    pass
  try:
    df_variables['Viento_medio (km/h)'] = round(df_variables['Viento_medio (km/h)'].astype(float)*1.60934, 2) # Convierto millas por hora a kilometros por hora
  except:
    pass
  df_variables['Fecha'] = fecha
  df_variables['Estacion'] = estacion

  #print(df_variables)
  return df_variables

